WB_PATH = "dsszzi/dsszzi-base-security-profile.xlsx"

wb = openpyxl.load_workbook(WB_PATH)
ws = wb["framework_content"]

# clear any existing content rows below header
if ws.max_row > 1:
    ws.delete_rows(2, ws.max_row - 1)

row_idx = 2
for family_name, items in FAMILIES:
    family_ref = FAMILY_REF_IDS[family_name]
    ws.cell(row=row_idx, column=1, value=False)   # assessable
    ws.cell(row=row_idx, column=2, value=1)        # depth
    ws.cell(row=row_idx, column=3, value=family_ref)  # ref_id
    ws.cell(row=row_idx, column=4, value=family_name)
    row_idx += 1
    for item_no, name, description, annotation in items:
        ref_id = item_no
        ws.cell(row=row_idx, column=1, value=True)
        ws.cell(row=row_idx, column=2, value=2)
        ws.cell(row=row_idx, column=3, value=ref_id)
        ws.cell(row=row_idx, column=4, value=name)
        ws.cell(row=row_idx, column=5, value=description)
        ws.cell(row=row_idx, column=6, value=annotation)
        ws.cell(row=row_idx, column=7, value=None)   # typical_evidence
        ws.cell(row=row_idx, column=8, value="VK, DSK")   # implementation_groups
        row_idx += 1

wb.save(WB_PATH)
print(f"Wrote {row_idx - 2} rows to framework_content")
